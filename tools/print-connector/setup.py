"""
MyPrint Local Print Connector
Interactive first-run setup wizard
"""

import os
import sys
import getpass
from pathlib import Path


def run_setup():
    """Interactive CLI setup wizard for first-time configuration."""

    print("\n" + "="*60)
    print("  MyPrint Local Print Connector — Setup Wizard")
    print("="*60)
    print("\nThis wizard will configure the connector to work with")
    print("your MyPrint shop. You'll need your shop login credentials.\n")

    # Step 1: Backend URL
    print("Step 1: Backend URL")
    print("-" * 40)
    default_url = "http://localhost:3000"
    backend_url = input(f"MyPrint backend URL [{default_url}]: ").strip()
    if not backend_url:
        backend_url = default_url

    # Step 2: Credentials
    print("\nStep 2: Shop Login Credentials")
    print("-" * 40)
    shop_email = input("Shop owner email: ").strip()
    shop_password = getpass.getpass("Shop owner password: ")

    # Step 3: Test connection
    print("\nStep 3: Testing connection…")
    print("-" * 40)

    try:
        import requests
        resp = requests.post(
            f"{backend_url}/api/auth/login",
            json={"email": shop_email, "password": shop_password},
            timeout=10,
        )
        if resp.status_code == 200:
            data = resp.json()
            shop_name = data.get("shop", {}).get("name", "your shop")
            shop_id = data.get("shop", {}).get("id", "")
            print(f"✔ Connected successfully! Shop: {shop_name}")
        else:
            print(f"✗ Login failed: {resp.status_code}")
            print(f"  Response: {resp.text[:200]}")
            print("\nPlease check your credentials and try again.")
            sys.exit(1)
    except Exception as e:
        print(f"✗ Could not connect to backend: {e}")
        print(f"\nMake sure the MyPrint server is running at: {backend_url}")
        sys.exit(1)

    # Step 4: Detect printers
    print("\nStep 4: Detecting installed printers…")
    print("-" * 40)

    printers = []
    if sys.platform == "win32":
        try:
            from printer_utils import get_installed_printers
            printers = get_installed_printers()
        except Exception as e:
            print(f"⚠ Could not detect printers: {e}")

    if printers:
        print(f"Found {len(printers)} printer(s):")
        for i, p in enumerate(printers, 1):
            default_mark = " [DEFAULT]" if p.get("isDefault") else ""
            print(f"  {i}. {p['name']}{default_mark}")
    else:
        print("⚠ No printers detected. You can add them later.")
        print("  Make sure printers are installed in Windows Settings.")

    # Step 5: Save config
    print("\nStep 5: Saving configuration…")
    print("-" * 40)

    import uuid
    connector_id = str(uuid.uuid4())

    env_content = f"""# MyPrint Local Print Connector — Auto-generated by setup.py
# Generated: {__import__('datetime').datetime.now().isoformat()}

BACKEND_URL={backend_url}
SHOP_EMAIL={shop_email}
SHOP_PASSWORD={shop_password}
SHOP_ID={shop_id}
CONNECTOR_ID={connector_id}
POLL_INTERVAL_SECONDS=5
MAX_RETRY_ATTEMPTS=3
LOG_LEVEL=INFO
TEMP_DIR=./temp_docs
"""

    env_path = Path(".env")
    env_path.write_text(env_content, encoding="utf-8")
    print(f"✔ Configuration saved to {env_path.absolute()}")

    print("\n" + "="*60)
    print("  Setup Complete!")
    print("="*60)
    print(f"\n  Shop:      {shop_name}")
    print(f"  Backend:   {backend_url}")
    print(f"  Connector: {connector_id[:8]}…")
    print(f"\n  To start the connector, run:")
    print(f"    python main.py")
    print("\n  The connector will automatically detect and queue")
    print("  print jobs from your MyPrint dashboard.\n")


if __name__ == "__main__":
    run_setup()

